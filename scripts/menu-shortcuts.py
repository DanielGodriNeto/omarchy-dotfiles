#!/usr/bin/env python3
"""Matches Omarchy menu items to the Hyprland keybinding that does the same thing.

Reads the stock and user menu definitions (omarchy-menu.jsonc) and the stock and
user bindings (Lua), and writes Shortcuts.js for the cloned menu plugin: a map
from menu item id to a shortcut string such as "SUPER SHIFT + F".

Usage: menu-shortcuts.py [output.js]   (default: the mancato.menu plugin folder)
Re-run after an Omarchy update, since menu items and bindings can change.
"""
import json
import re
import sys
from pathlib import Path

HOME = Path.home()
MENU_FILES = [
    Path("/usr/share/omarchy/default/omarchy/omarchy-menu.jsonc"),
    HOME / ".config/omarchy/extensions/omarchy-menu.jsonc",
]
BIND_FILES = sorted(Path("/usr/share/omarchy/default/hypr/bindings").glob("*.lua")) + [
    HOME / ".config/hypr/bindings.lua",
]
DEFAULT_OUT = HOME / ".config/omarchy/plugins/mancato.menu/Shortcuts.js"

ITEM = re.compile(r'^\s*"([\w.\-]+)":\s*(\{.*\}),?\s*$')
BIND = re.compile(r'^\s*o\.bind(?:_toggle)?\(\s*"([^"]+)"\s*,\s*(?:"[^"]*"|nil)\s*,\s*(.+?)\s*(?:,\s*\{[^}]*\})?\s*\)\s*$')
MENU_TARGET = re.compile(r'^\{\s*menu\s*=\s*"([\w\-]+)"\s*\}$')
STRING = re.compile(r'^"([^"]+)"$')

# Bindings whose command is a compound line that never equals a menu action.
EXTRA = {"trigger.capture.screenrecord": "ALT + PRINT"}


def read_menu():
    items = {}
    for path in MENU_FILES:
        if not path.exists():
            continue
        for line in path.read_text().splitlines():
            match = ITEM.match(line)
            if not match:
                continue
            try:
                items[match.group(1)] = json.loads(match.group(2))
            except json.JSONDecodeError:
                pass
    return items


def read_binds():
    """Returns ({command: [keys]}, {menu_target: [keys]})."""
    by_command, by_menu = {}, {}
    for path in BIND_FILES:
        if not path.exists():
            continue
        for line in path.read_text().splitlines():
            match = BIND.match(line)
            if not match:
                continue
            keys, target = match.group(1), match.group(2)
            menu = MENU_TARGET.match(target)
            if menu:
                by_menu.setdefault(menu.group(1), []).append(keys)
                continue
            text = STRING.match(target)
            if text:
                by_command.setdefault(text.group(1), []).append(keys)
    return by_command, by_menu


def best(keys):
    """The shortest combination, which is the easiest to press."""
    return sorted(keys, key=lambda k: (len(k.replace(" ", "").split("+")[0]), len(k)))[0]


def main():
    items = read_menu()
    by_command, by_menu = read_binds()
    result = {}
    for item_id, item in items.items():
        action = (item.get("action") or "").strip()
        if action and action in by_command:
            result[item_id] = best(by_command[action])
            continue
        for target, keys in by_menu.items():
            if item_id in (target, "trigger." + target, "appearance." + target):
                result[item_id] = best(keys)
                break
    for item_id, keys in EXTRA.items():
        if item_id in items:
            result[item_id] = keys
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    body = json.dumps(dict(sorted(result.items())), indent=2, ensure_ascii=False)
    out.write_text(".pragma library\n\n// Generated by scripts/menu-shortcuts.py: menu item id -> Hyprland shortcut.\nvar SHORTCUTS = " + body + "\n\nfunction of(id) {\n  return SHORTCUTS[String(id || \"\")] || \"\"\n}\n")
    print(f"{len(result)} shortcuts from {len(items)} menu items -> {out}")
    for item_id, keys in sorted(result.items()):
        print(f"  {item_id:34} {keys}")


if __name__ == "__main__":
    main()
